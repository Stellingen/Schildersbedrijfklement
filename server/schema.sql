CREATE TABLE IF NOT EXISTS admins (username VARCHAR(80) PRIMARY KEY, password_hash VARCHAR(255) NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS sessions (token_hash CHAR(64) PRIMARY KEY, username VARCHAR(80) NOT NULL, csrf CHAR(64) NOT NULL, expires_at DATETIME NOT NULL, INDEX session_expiry (expires_at));
CREATE TABLE IF NOT EXISTS settings (setting_key VARCHAR(80) PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS rate_limits (bucket CHAR(64) PRIMARY KEY, hits INT NOT NULL DEFAULT 1, expires_at DATETIME NOT NULL, INDEX rate_expiry (expires_at));
CREATE TABLE IF NOT EXISTS enquiries (
 id CHAR(36) PRIMARY KEY, reference VARCHAR(20) UNIQUE NOT NULL, name VARCHAR(80) NOT NULL, email VARCHAR(120) NOT NULL, phone VARCHAR(24) NOT NULL,
 place VARCHAR(80) NOT NULL, planning VARCHAR(80) NOT NULL, property VARCHAR(80) NOT NULL, description TEXT NOT NULL,
 services JSON NOT NULL, color JSON NULL, consent_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 status VARCHAR(20) NOT NULL DEFAULT 'nieuw', notes TEXT NOT NULL, follow_up DATE NULL,
 email_status VARCHAR(20) NOT NULL DEFAULT 'pending', email_attempts INT NOT NULL DEFAULT 0, last_email_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX enquiry_date (created_at), INDEX enquiry_status (status)
);
CREATE TABLE IF NOT EXISTS media (
 id VARCHAR(40) PRIMARY KEY, photo_id VARCHAR(60) NOT NULL, title VARCHAR(120) NOT NULL, caption VARCHAR(400) NOT NULL, alt VARCHAR(240) NOT NULL,
 album VARCHAR(20) NOT NULL, src VARCHAR(200) NOT NULL, in_gallery BOOLEAN NOT NULL DEFAULT 0, published BOOLEAN NOT NULL DEFAULT 1,
 sort_order INT NOT NULL DEFAULT 0, image_data MEDIUMBLOB NULL, bytes INT NOT NULL DEFAULT 0, etag CHAR(64) NULL,
 deleted_at DATETIME NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS site_slots (slot_key VARCHAR(40) PRIMARY KEY, media_id VARCHAR(40) NULL);
CREATE TABLE IF NOT EXISTS page_views (
 event_id CHAR(36) PRIMARY KEY, day DATE NOT NULL, visitor CHAR(64) NOT NULL, path VARCHAR(160) NOT NULL,
 source VARCHAR(120) NOT NULL, device VARCHAR(12) NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX views_day (day), INDEX views_visitor (day,visitor)
);
CREATE TABLE IF NOT EXISTS activity (id BIGINT AUTO_INCREMENT PRIMARY KEY, action VARCHAR(200) NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP);
